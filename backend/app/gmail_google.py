"""Official Google HTTPS endpoints only; bounded requests, safe errors, no mail logging."""
import json
import time
from urllib.parse import quote, urlsplit
from cryptography.fernet import Fernet, InvalidToken
import httpx
from fastapi import HTTPException
from .config import settings

SCOPE='https://www.googleapis.com/auth/gmail.readonly'
TOKEN_URL='https://oauth2.googleapis.com/token'
REVOKE_URL='https://oauth2.googleapis.com/revoke'
API='https://gmail.googleapis.com/gmail/v1/users/me/'


class GoogleFailure(Exception):
    def __init__(self,kind='unavailable'):
        self.kind=kind
        super().__init__('Gmail authorization expired; reconnect.' if kind=='revoked' else 'Gmail is temporarily unavailable; try again later.')


def cipher():
    try:return Fernet(settings().gmail_encryption_key.get_secret_value().encode())
    except (ValueError,TypeError):raise HTTPException(503,'Gmail token encryption is not configured') from None


def configured():
    config=settings()
    if not config.google_client_id or not config.google_client_secret.get_secret_value():
        raise HTTPException(503,'Configure Google OAuth credentials and Gmail encryption on the server first')
    cipher()
    for value in [config.gmail_redirect_uri,config.gmail_frontend_url]:
        parts=urlsplit(value)
        if not parts.hostname or parts.username or parts.password or parts.query or parts.fragment or (parts.scheme!='https' and not (parts.scheme=='http' and parts.hostname in {'localhost','127.0.0.1'})):
            raise HTTPException(503,'Gmail redirect URLs require HTTPS (HTTP loopback is allowed for local development)')
    if urlsplit(config.gmail_redirect_uri).path!='/api/gmail/oauth/callback':
        raise HTTPException(503,'Gmail OAuth callback path is misconfigured')
    if config.gmail_frontend_url.rstrip('/') not in [origin.strip().rstrip('/') for origin in config.cors_origins.split(',')]:
        raise HTTPException(503,'Gmail frontend URL must match an allowed frontend origin')
    return config


def encrypt(owner,value):
    return cipher().encrypt(json.dumps({'owner':str(owner),'value':value}).encode()).decode()


def decrypt(owner,value):
    try:
        data=json.loads(cipher().decrypt(value.encode()))
        if data['owner']!=str(owner):raise ValueError()
        return data['value']
    except (InvalidToken,ValueError,KeyError,TypeError,AttributeError):
        raise HTTPException(503,'Gmail credentials cannot be decrypted; restore the encryption key or reconnect') from None


class GoogleClient:
    def __init__(self,access_token=None):
        self.access_token=access_token
        self.deadline=time.monotonic()+45
        self.requests=0
    def call(self,method,url,**kwargs):
        # Fixed URLs generated by this module; never follow remote redirects.
        if url not in {TOKEN_URL,REVOKE_URL} and not url.startswith(API):raise GoogleFailure()
        for attempt in range(3):
            left=self.deadline-time.monotonic()
            if left<=0 or self.requests>=35:raise GoogleFailure('paused')
            self.requests+=1
            try:
                with httpx.Client(timeout=min(10,left),follow_redirects=False,trust_env=False) as client:
                    with client.stream(method,url,**kwargs) as response:
                        if response.status_code in {429,500,502,503,504}:
                            if attempt<2:
                                try:delay=min(2,max(0,float(response.headers.get('Retry-After',2**attempt))))
                                except ValueError:delay=1
                                if time.monotonic()+delay>=self.deadline:raise GoogleFailure('rate_limited')
                                time.sleep(delay);continue
                            raise GoogleFailure('rate_limited')
                        raw=bytearray()
                        for chunk in response.iter_bytes():
                            raw.extend(chunk)
                            if len(raw)>4*1024*1024 or time.monotonic()>self.deadline:raise GoogleFailure('paused')
                        try:data=json.loads(raw) if raw else {}
                        except (ValueError,RecursionError):raise GoogleFailure() from None
                        if not isinstance(data,dict):raise GoogleFailure()
                        if response.status_code==404:raise GoogleFailure('not_found')
                        if response.status_code==400 and (kwargs.get('params') or {}).get('pageToken'):
                            raise GoogleFailure('invalid_page')
                        if response.status_code in {400,401}:
                            raise GoogleFailure('revoked' if response.status_code==401 or data.get('error')=='invalid_grant' else 'unavailable')
                        if response.status_code==403:
                            reasons=[e.get('reason') for e in data.get('error',{}).get('errors',[]) ] if isinstance(data.get('error'),dict) else []
                            raise GoogleFailure('rate_limited' if any(r in {'rateLimitExceeded','userRateLimitExceeded','quotaExceeded'} for r in reasons) else 'permission_denied')
                        if not 200<=response.status_code<300 or not isinstance(data,dict):raise GoogleFailure()
                        return data
            except httpx.HTTPError:raise GoogleFailure() from None
        raise GoogleFailure()
    def exchange(self,code,verifier):
        config=configured()
        return self.call('POST',TOKEN_URL,data={'code':code,'code_verifier':verifier,'client_id':config.google_client_id,'client_secret':config.google_client_secret.get_secret_value(),'redirect_uri':config.gmail_redirect_uri,'grant_type':'authorization_code'})
    def refresh(self,refresh_token):
        config=configured()
        result=self.call('POST',TOKEN_URL,data={'refresh_token':refresh_token,'client_id':config.google_client_id,'client_secret':config.google_client_secret.get_secret_value(),'grant_type':'refresh_token'})
        if not result.get('access_token'):raise GoogleFailure('revoked')
        if 'scope' in result and SCOPE not in result['scope'].split():raise GoogleFailure('permission_denied')
        self.access_token=result['access_token']
        return result
    def get(self,path,params=None):
        if not self.access_token:raise GoogleFailure('revoked')
        return self.call('GET',API+path,params=params,headers={'Authorization':'Bearer '+self.access_token})
    def profile(self):return self.get('profile')
    def messages(self,query,page=None):return self.get('messages',{'q':query,'maxResults':25,**({'pageToken':page} if page else {})})
    def history(self,start,page=None):return self.get('history',{'startHistoryId':start,'historyTypes':'messageAdded','maxResults':25,**({'pageToken':page} if page else {})})
    def message(self,id):return self.get('messages/'+quote(id,safe=''),{'format':'full'})
    def revoke(self,token):
        try:self.call('POST',REVOKE_URL,data={'token':token})
        except GoogleFailure:pass
